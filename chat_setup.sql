-- Kenzz Store Community Chat setup
-- Jalankan di Supabase Dashboard > SQL Editor.
-- Chat ini publik: pesan dapat dibaca semua pengunjung dan nickname bukan identitas terverifikasi.
create table if not exists public.kenzz_chat_messages (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(btrim(nickname)) between 1 and 30),
  message text not null check (char_length(btrim(message)) between 1 and 1000),
  created_at timestamptz not null default now()
);
create index if not exists kenzz_chat_messages_created_at_idx on public.kenzz_chat_messages (created_at desc);
alter table public.kenzz_chat_messages enable row level security;
drop policy if exists "Public can read Kenzz chat" on public.kenzz_chat_messages;
create policy "Public can read Kenzz chat" on public.kenzz_chat_messages for select to anon, authenticated using (true);
drop policy if exists "Public can send Kenzz chat messages" on public.kenzz_chat_messages;
create policy "Public can send Kenzz chat messages" on public.kenzz_chat_messages for insert to anon, authenticated with check (
  char_length(btrim(nickname)) between 1 and 30 and
  char_length(btrim(message)) between 1 and 1000
);
-- Enable realtime for live updates. Safe to run if already a member of publication:
do $$ begin
  execute 'alter publication supabase_realtime add table public.kenzz_chat_messages';
exception when duplicate_object then null;
when undefined_object then raise notice 'Publication supabase_realtime not found; enable Realtime for this table in Supabase Dashboard.';
end $$;
